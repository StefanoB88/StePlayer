// Builds the TV web app: bundles src/main.ts for the oldest supported TV engine, generates the icon module and
// copies the static files.
//   Samsung (default): build/        Chromium 56 = Tizen 4.0 (2018 models), static/ (config.xml, index.html, icon)
//   LG (--webos):      build-webos/  Chromium 53 = webOS 4.0 (2018 models), static/styles.css + webos/ (appinfo.json,
//                                    index.html, icons, splash)
//   LG Full HD (--webos --r720): build-webos-720/, same app for TVs whose graphics plane is 1280×720: appinfo
//                                    "resolution": "1280x720" and <html class="r720"> (layout scaled to 2/3)
// Usage: node scripts/build.mjs [--webos [--r720]] [--watch] [--dev]
import { build, context } from 'esbuild';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const webos = process.argv.includes('--webos');
const r720 = webos && process.argv.includes('--r720');
const out = join(root, webos ? (r720 ? 'build-webos-720' : 'build-webos') : 'build');
const watch = process.argv.includes('--watch');
const dev = process.argv.includes('--dev') || watch;

// Material Symbols "round" set (Apache-2.0), the same icon family as the Android app.
const ICONS = [
  'home', 'live_tv', 'movie', 'video_library', 'search', 'settings', 'play_arrow', 'pause', 'replay_10',
  'forward_10', 'info', 'refresh', 'star', 'history', 'favorite', 'favorite_border', 'arrow_back', 'list',
  'audiotrack', 'closed_caption', 'aspect_ratio', 'tune', 'speed', 'calendar_view_week', 'swap_horiz', 'close',
  'wifi_off', 'skip_next', 'replay', 'add', 'remove', 'check', 'radio_button_checked', 'radio_button_unchecked',
  'edit', 'delete', 'visibility', 'visibility_off', 'error_outline', 'bedtime', 'video_library', 'tv',
  'lock', 'expand_more', 'chevron_right', 'keyboard', 'check_circle', 'cloud_sync', 'notes',
];

function generateIcons() {
  const dir = join(root, 'node_modules/@material-design-icons/svg/round');
  const entries = [...new Set(ICONS)].map((name) => {
    const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
    const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    return `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},`;
  });
  const file = join(root, 'src/ui/iconData.ts');
  const content = `// Generated by scripts/build.mjs from @material-design-icons/svg (round, Apache-2.0). Do not edit.\n` +
    `export const ICON_PATHS: Record<string, string> = {\n${entries.join('\n')}\n};\n`;
  if (!existsSync(file) || readFileSync(file, 'utf8') !== content) writeFileSync(file, content);
}

function copyStatic() {
  mkdirSync(out, { recursive: true });
  if (!webos) { cpSync(join(root, 'static'), out, { recursive: true }); return; }
  // webOS: same styles; its own manifest, page (no Samsung webapis.js) and images.
  cpSync(join(root, 'static/styles.css'), join(out, 'styles.css'));
  cpSync(join(root, 'webos'), out, { recursive: true });
  if (r720) {
    const info = JSON.parse(readFileSync(join(out, 'appinfo.json'), 'utf8'));
    info.resolution = '1280x720';
    writeFileSync(join(out, 'appinfo.json'), `${JSON.stringify(info, null, 2)}\n`);
    const page = join(out, 'index.html');
    writeFileSync(page, readFileSync(page, 'utf8').replace('<html lang="it">', '<html lang="it" class="r720">')
      .replace('width=1920, height=1080', 'width=1280, height=720'));
  }
}

generateIcons();
rmSync(out, { recursive: true, force: true });
copyStatic();

const options = {
  entryPoints: [join(root, 'src/main.ts')],
  bundle: true,
  outfile: join(out, 'app.js'),
  format: 'iife',
  target: [webos ? 'chrome53' : 'chrome56'],
  minify: !dev,
  sourcemap: dev ? 'inline' : false,
  legalComments: 'none',
  define: { __DEV__: JSON.stringify(dev) },
  logLevel: 'info',
};

if (watch) {
  const ctx = await context(options);
  await ctx.watch();
  console.log('watching…');
} else {
  await build(options);
}
