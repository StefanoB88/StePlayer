// Builds the Tizen web app into build/: bundles src/main.ts for the oldest supported TV engine
// (Chromium 56 = Tizen 4.0, 2018 models), generates the icon module and copies the static files.
// Usage: node scripts/build.mjs [--watch] [--dev]
import { build, context } from 'esbuild';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'build');
const watch = process.argv.includes('--watch');
const dev = process.argv.includes('--dev') || watch;

// Material Symbols "round" set (Apache-2.0), the same icon family as the Android app.
const ICONS = [
  'home', 'live_tv', 'movie', 'video_library', 'search', 'settings', 'play_arrow', 'pause', 'replay_10',
  'forward_10', 'info', 'refresh', 'star', 'history', 'favorite', 'favorite_border', 'arrow_back', 'list',
  'audiotrack', 'closed_caption', 'aspect_ratio', 'tune', 'speed', 'calendar_view_week', 'swap_horiz', 'close',
  'wifi_off', 'skip_next', 'replay', 'add', 'remove', 'check', 'radio_button_checked', 'radio_button_unchecked',
  'edit', 'delete', 'visibility', 'visibility_off', 'error_outline', 'bedtime', 'video_library', 'tv',
  'lock', 'expand_more', 'chevron_right', 'keyboard', 'check_circle', 'cloud_sync', 'notes',
];

function generateIcons() {
  const dir = join(root, 'node_modules/@material-design-icons/svg/round');
  const entries = [...new Set(ICONS)].map((name) => {
    const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
    const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    return `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},`;
  });
  const file = join(root, 'src/ui/iconData.ts');
  const content = `// Generated by scripts/build.mjs from @material-design-icons/svg (round, Apache-2.0). Do not edit.\n` +
    `export const ICON_PATHS: Record<string, string> = {\n${entries.join('\n')}\n};\n`;
  if (!existsSync(file) || readFileSync(file, 'utf8') !== content) writeFileSync(file, content);
}

function copyStatic() {
  mkdirSync(out, { recursive: true });
  cpSync(join(root, 'static'), out, { recursive: true });
}

generateIcons();
rmSync(out, { recursive: true, force: true });
copyStatic();

const options = {
  entryPoints: [join(root, 'src/main.ts')],
  bundle: true,
  outfile: join(out, 'app.js'),
  format: 'iife',
  target: ['chrome56'],
  minify: !dev,
  sourcemap: dev ? 'inline' : false,
  legalComments: 'none',
  define: { __DEV__: JSON.stringify(dev) },
  logLevel: 'info',
};

if (watch) {
  const ctx = await context(options);
  await ctx.watch();
  console.log('watching…');
} else {
  await build(options);
}
